import assert from 'node:assert/strict';
import {ITEMS} from '../src/catalog.js';
import {isAnimal,ownedAnimals} from '../src/animals.js';
import {isPen,penSpecies,penResidents,eggCollection} from '../src/pens.js';
import {GoatLife} from '../public/style-preview/goat-life.js';
assert.equal(ITEMS.cat.cost,8);assert.equal(ITEMS.cat.refund,4);
assert.equal(ITEMS.cat_home.cost,12);assert.equal(ITEMS.cat_home.refund,6);
const home={id:'home',item_type:'cat_home',slot_index:5};
const cats=[{id:'cat',item_type:'cat',slot_index:0,pen_item_id:'home'}];
const oasis={items:[home,...cats],land_level:1};
assert.ok(isAnimal('cat'));assert.ok(isPen('cat_home'));assert.equal(penSpecies(home),'cat');
assert.equal(ownedAnimals(oasis).length,1);assert.equal(penResidents(oasis,home).length,1);
assert.equal(eggCollection(oasis).count,0,'cats do not create eggs');
const nav={project:p=>({point:p}),pathTo:(a,b)=>[{...b}]};
const life=new GoatLife(false,{x:100,y:100},nav),player={x:600,y:400},bed={x:100,y:100},door={x:150,y:150};
life.update(.05,1,player,bed,door,false);
life.update(.05,2,player,bed,door,true);
assert.equal(life.mode,'joining');
for(let t=3;t<300;t++)life.update(.05,t*50,player,bed,door,true);
assert.equal(life.mode,'following');
const before={x:life.x,y:life.y};life.update(.05,16000,player,bed,door,false);
assert.equal(life.mode,'returning');assert.ok(Math.hypot(life.x-before.x,life.y-before.y)<12,'cat walks home instead of teleporting');
for(let t=321;t<600;t++)life.update(.05,t*50,player,bed,door,false);
assert.equal(life.mode,'home');assert.ok(Math.hypot(life.x-bed.x,life.y-bed.y)<20);
console.log('PASS: cat prices, species home, no cat eggs, following and physical walk home.');
